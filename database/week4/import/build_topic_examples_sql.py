#!/usr/bin/env python3
"""Generate the SQL patch for bilingual examples in the curated topic decks."""

import csv
import re
from pathlib import Path

from build_import_sql import sql_text

DATA = Path(__file__).resolve().parent / "data"


def build_sql():
    with (DATA / "topic_word_review.csv").open(encoding="utf-8", newline="") as file:
        missing = [row for row in csv.DictReader(file)
                   if not row["example_en"].strip() and not row["example_vi"].strip()]
    with (DATA / "topic_examples.tsv").open(encoding="utf-8", newline="") as file:
        examples = list(csv.DictReader(file, delimiter="\t"))
    by_word = {example["headword"]: example for example in examples}
    if len(by_word) != len(examples) or len(by_word) != len(missing) or set(by_word) != {row["headword"] for row in missing}:
        raise ValueError("The example dataset must cover exactly the missing topic words")

    rows = []
    for word in missing:
        headword = word["headword"]
        example = by_word[headword]
        if not re.search(rf"\b{re.escape(headword)}\b", example["en"], re.IGNORECASE) or not example["vi"].strip():
            raise ValueError(f"Invalid bilingual example for {headword}")
        values = (word["import_key"], headword, word["meaning_vi"], example["en"].strip(), example["vi"].strip())
        rows.append("(" + ", ".join(map(sql_text, values)) + ")")
    values_sql = ",\n".join(rows)
    return f"""-- Generated by build_topic_examples_sql.py. Apply after the topic vocabulary import.
-- Existing examples and word senses are left intact.
BEGIN;
SET LOCAL standard_conforming_strings = on;
WITH examples(import_key, headword, meaning_vi, example_en, example_vi) AS (
    VALUES
{values_sql}
)
UPDATE public.words w
SET example_en = e.example_en,
    example_vi = e.example_vi,
    source_metadata = jsonb_set(w.source_metadata, '{{examples}}',
        jsonb_build_object('english', 'English Learning App (original example)',
                           'vietnamese', 'English Learning App (example translation)'))
FROM examples e
WHERE w.import_key = e.import_key AND w.headword = e.headword AND w.meaning_vi = e.meaning_vi
  AND NULLIF(btrim(w.example_en), '') IS NULL AND NULLIF(btrim(w.example_vi), '') IS NULL;
COMMIT;
"""


if __name__ == "__main__":
    (DATA / "apply_topic_examples.sql").write_text(build_sql(), encoding="utf-8")
